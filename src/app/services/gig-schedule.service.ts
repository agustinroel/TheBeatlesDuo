@Injectable({
  providedIn: 'root',
})
export class GigScheduleService {
  readonly allGigs = signal<readonly GigEvent[]>(INITIAL_2027_GIGS);
  readonly activeVenueFilter = signal<VenueFilter>('ALL');
  readonly highlightedGigId = signal<string | null>(null);

  readonly venueFilters: readonly { readonly value: VenueFilter; readonly label: string; readonly city: string }[] = [
    { value: 'ALL', label: 'Todas las fechas', city: '26 directos' },
    { value: "Paddy's Point", label: "Paddy's Point", city: 'Torrevieja' },
    { value: 'Saxo', label: 'Saxo', city: 'Moraira' },
    { value: 'The Robins', label: 'The Robins', city: 'Alicante' },
    { value: 'Puerta Falsa', label: 'Puerta Falsa', city: 'Murcia' },
  ];

  readonly filteredGigs = computed(() => {
    const filter = this.activeVenueFilter();
    const list = this.allGigs();
    if (filter === 'ALL') {
      return list;
    }
    return list.filter((gig) => gig.venue === filter);
  });

  readonly totalFilteredCount = computed(() => this.filteredGigs().length);

  setVenueFilter(filter: VenueFilter): void {
    this.activeVenueFilter.set(filter);
  }

  setHighlightedGig(id: string | null): void {
    this.highlightedGigId.set(id);
  }
}
